#!/usr/bin/env node
/**
 * Generate one TypeScript file per asset type from a meta.v1 metamodel.
 *
 *   npm run generate:types                       # reads ./metamodel.json, writes src/types/assets/
 *   node scripts/generate-types.mjs <metamodel.json> [outDir]
 *
 * What the output is:
 *   - src/types/assets/<Token>.ts: `export interface <Token> extends <Base>`
 *     with the attributes the type DEFINES ITSELF (an attribute the type
 *     inherits carries a `Base` pointing at the defining ancestor; an
 *     attribute with no `Base` is the type's own). The extends chain is the
 *     metamodel's Base chain; a type with no Base extends the hand-written
 *     Asset root (src/types/asset.ts).
 *   - src/types/assets/index.ts: every type re-exported, the AssetTypeName
 *     union, and an AssetTypeMap from token to interface.
 *
 * What the output is not:
 *   - endpoint-aware. A relation is a Ref (or Ref[]); how api/asset, query.v1
 *     and rest-1 spell a relation on the wire is the wire layer's business.
 *   - instance-specific. An instance's own custom attributes (IsCustom and
 *     not IsCanned; always Custom_-prefixed) are not generated; the Asset
 *     root carries them through a `Custom_${string}` index signature. The
 *     product's canned "custom" attributes (IsCanned and IsCustom both true)
 *     ship everywhere and are generated like any other.
 *   - hand-editable. Regenerate; a snapshot test fails if the committed
 *     files drift from the committed metamodel.
 */
import { mkdir, readFile, writeFile, readdir, rm } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));

/** meta.v1 AttributeType -> the model's TypeScript type. */
const SCALAR = {
  Text: "string",
  LongText: "string",
  LocalizerTag: "string",
  Password: "string",
  Opaque: "string",
  Guid: "string",
  Duration: "string",
  Rank: "string",
  Date: "DateString",
  Numeric: "number",
  LongInt: "number",
  Boolean: "boolean",
  State: "AssetStateValue"
};

const HEADER = (version, count) => `// Generated by scripts/generate-types.mjs from metamodel.json (meta.v1 ${version}); do not edit.
// ${count} attributes the type defines itself; inherited ones come through extends.
`;

/**
 * The asset types that describe the metamodel itself. They are not generated:
 * src/types/metamodel.ts models what meta.v1 DELIVERS for them (Token,
 * DisplayName, IsMultivalue, RelatedAsset, Base …), which is a different
 * vocabulary from the attribute set those asset types declare (NativeValue,
 * IsBasic, History …), and generating both would put two AssetType and two
 * AttributeDefinition interfaces in src/types. checkHandwritten() watches
 * the hand-written ones for drift from the delivered document instead.
 */
export const META_TYPES = new Set(["AssetType", "AttributeDefinition", "RelationDefinition", "BaseSyntheticAttributeDefinition", "Override", "Operation", "PrimaryRelation", "BaseRule", "InsertUpdateRule", "EventDefinition"]);

/**
 * Do the hand-written metamodel types still match what meta.v1 delivers?
 * Compares the fields of `AssetType` and `AttributeDefinition` in
 * src/types/metamodel.ts with the keys actually present on the delivered
 * documents in the metamodel — a reference-valued key ({ tokenref } /
 * { nameref }) counts under its own name, since the model keeps the token.
 * Returns, per type, the hand-written fields the document never carries
 * (phantoms: a field nothing will ever fill) and the delivered keys the
 * hand-written type omits (unmodelled: information callers cannot reach).
 * Keys that are deliberately not modelled are listed in IGNORED.
 */
const IGNORED = new Set(["HREF", "Version", "Operations", "Rules", "Description", "Name"]);
export function checkHandwritten(metamodel, metamodelTs) {
  const types = metamodel.AssetTypes;
  const delivered = { AssetType: new Set(), AttributeDefinition: new Set() };
  for (const t of Object.values(types)) {
    for (const k of Object.keys(t)) delivered.AssetType.add(k);
    for (const a of Object.values(t.Attributes ?? {})) for (const k of Object.keys(a)) delivered.AttributeDefinition.add(k);
  }
  const report = {};
  for (const name of ["AssetType", "AttributeDefinition"]) {
    const m = metamodelTs.match(new RegExp(`export interface ${name}\\s*\\{([\\s\\S]*?)\\n\\}`));
    const fields = m ? [...m[1].matchAll(/^\s*(?:readonly\s+)?(\w+)\??:/gm)].map((x) => x[1]) : [];
    const seen = delivered[name];
    report[name] = {
      phantoms: fields.filter((f) => f !== "_type" && !seen.has(f)),
      unmodelled: [...seen].filter((k) => !fields.includes(k) && !IGNORED.has(k)).sort()
    };
  }
  return report;
}

/** Build the model from the metamodel JSON: what to emit per type, in dependency-safe order. */
export function model(metamodel) {
  const types = metamodel.AssetTypes;
  const tokens = Object.keys(types).filter((t) => !META_TYPES.has(t)).sort();
  const baseOf = (token) => types[token].Base?.nameref ?? null;
  const concrete = tokens.filter((t) => !types[t].Abstract);
  // Every concrete descendant of a type, itself included when concrete.
  const descendants = (token) => concrete.filter((c) => { for (let t = c; t; t = baseOf(t)) if (t === token) return true; return false; });

  const files = tokens.map((token) => {
    const type = types[token];
    // Own (no Base), canned (ships on every instance — 34 canned attributes
    // are also flagged IsCustom, product history: Reference, Source,
    // RequestedBy, LastVersion, OriginalEstimate and the *Source reverse
    // lists; they stay), a field rather than a joined path, and a value the
    // model can carry (a Blob is bytes behind another endpoint).
    const own = Object.values(type.Attributes)
      .filter((a) => !a.Base && a.IsCanned !== false && !a.Name.includes(".") && a.AttributeType !== "Blob")
      .sort((a, b) => a.Name.localeCompare(b.Name));
    const imports = new Set();
    const lines = own.map((a) => {
      let tsType;
      if (a.AttributeType === "Relation") {
        const target = a.RelatedAsset.nameref;
        // A relation to a meta-describing type (an AssetType, an Operation)
        // is a bare Ref: those types are not generated.
        if (META_TYPES.has(target)) tsType = a.IsMultivalue ? "Ref[]" : "Ref";
        else {
          if (target !== token) imports.add(target);
          tsType = a.IsMultivalue ? `Ref<${target}>[]` : `Ref<${target}>`;
        }
      } else if (a.AttributeType === "AssetType") {
        const names = descendants(token);
        tsType = names.length ? names.map((n) => JSON.stringify(n)).join(" | ") : "string";
      } else {
        tsType = SCALAR[a.AttributeType];
        if (!tsType) throw new Error(`${a.Token}: no mapping for AttributeType ${a.AttributeType}`);
      }
      // A single value the server may leave unset reads back as null; a
      // multi-value reads back as an array; a required value is never null.
      const nullable = !a.IsMultivalue && !a.IsRequired && a.AttributeType !== "AssetType";
      const doc = [a.IsReadOnly ? "read-only" : null, a.IsRequired ? "required" : null].filter(Boolean).join(", ");
      return `  ${a.IsReadOnly ? "readonly " : ""}${a.Name}${nullable ? "?" : ""}: ${tsType}${nullable ? " | null" : ""};${doc ? ` // ${doc}` : ""}`;
    });
    const parent = baseOf(token);
    const base = parent && !META_TYPES.has(parent) ? parent : "Asset";
    if (base !== "Asset") imports.add(base);
    imports.delete(token);
    const importLines = [
      `import type { Asset, Ref, DateString, AssetStateValue } from "../asset";`,
      ...[...imports].sort().map((t) => `import type { ${t} } from "./${t}";`)
    ];
    const body = [
      `export interface ${token} extends ${base} {`,
      ...lines,
      `}`
    ];
    return { token, ownCount: own.length, text: `${HEADER(metamodel.Version, own.length)}${importLines.join("\n")}\n\n${body.join("\n")}\n` };
  });

  const index = [
    `// Generated by scripts/generate-types.mjs from metamodel.json (meta.v1 ${metamodel.Version}); do not edit.`,
    ...tokens.map((t) => `export type { ${t} } from "./${t}";`),
    ``,
    `/** Every asset type token the metamodel defines, abstract ones included. */`,
    `export type AssetTypeName =`,
    ...tokens.map((t, i) => `  ${i === 0 ? "" : "| "}${JSON.stringify(t)}`),
    `  ;`,
    ``,
    `/** The concrete (instantiable) asset type tokens. */`,
    `export type ConcreteAssetTypeName =`,
    ...concrete.map((t, i) => `  ${i === 0 ? "" : "| "}${JSON.stringify(t)}`),
    `  ;`,
    ``,
    `/** Token to interface, for typing a lookup by AssetType. */`,
    `export interface AssetTypeMap {`,
    ...tokens.map((t) => `  ${t}: import("./${t}").${t};`),
    `}`,
    ``
  ].join("\n");

  return { files, index, count: tokens.length, attributes: files.reduce((n, f) => n + f.ownCount, 0) };
}

export async function generate(metamodelPath, outDir) {
  const metamodel = JSON.parse(await readFile(metamodelPath, "utf8"));
  const { files, index, count, attributes } = model(metamodel);
  await rm(outDir, { recursive: true, force: true });
  await mkdir(outDir, { recursive: true });
  await Promise.all(files.map((f) => writeFile(join(outDir, `${f.token}.ts`), f.text)));
  await writeFile(join(outDir, "index.ts"), index);
  return { count, attributes, written: (await readdir(outDir)).length };
}

const isMain = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const [, , metamodelArg, outArg] = process.argv;
  const metamodelPath = resolve(metamodelArg ?? join(here, "..", "metamodel.json"));
  const outDir = resolve(outArg ?? join(here, "..", "src", "types", "assets"));
  generate(metamodelPath, outDir)
    .then(async ({ count, attributes, written }) => {
      console.log(`${count} asset types, ${attributes} own attributes -> ${written} files in ${outDir}`);
      // The meta-describing types are hand-written; say whether they still match what meta.v1 delivers.
      const report = checkHandwritten(JSON.parse(await readFile(metamodelPath, "utf8")), await readFile(join(here, "..", "src", "types", "metamodel.ts"), "utf8"));
      for (const [name, { phantoms, unmodelled }] of Object.entries(report)) {
        if (phantoms.length) console.warn(`${name}: hand-written fields meta.v1 never delivers: ${phantoms.join(", ")}`);
        if (unmodelled.length) console.log(`${name}: delivered keys not modelled (fine if deliberate): ${unmodelled.join(", ")}`);
      }
    })
    .catch((e) => { console.error(e.message); process.exitCode = 1; });
}
